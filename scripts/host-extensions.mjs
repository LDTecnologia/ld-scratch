// Keep extension code and the micro:bit firmware in this repository.
// Restores vendor/extensions over the installed scratch-vm copy after install,
// so a later scratch-vm release cannot replace the blocks this editor ships.
import fs from 'fs';
import path from 'path';
import {fileURLToPath} from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const copyIfDifferent = (source, destination) => {
    fs.mkdirSync(destination, {recursive: true});
    for (const entry of fs.readdirSync(source, {withFileTypes: true})) {
        const from = path.join(source, entry.name);
        const to = path.join(destination, entry.name);
        if (entry.isDirectory()) {
            copyIfDifferent(from, to);
            continue;
        }
        const next = fs.readFileSync(from);
        if (fs.existsSync(to) && fs.readFileSync(to).equals(next)) {
            continue;
        }
        fs.writeFileSync(to, next);
    }
};

const restoreBundledExtensions = () => {
    const vendorDir = path.join(root, 'vendor', 'extensions');
    const installedDir = path.join(root, 'node_modules', 'scratch-vm', 'src', 'extensions');
    if (!fs.existsSync(vendorDir) || !fs.existsSync(path.dirname(installedDir))) {
        return;
    }
    copyIfDifferent(vendorDir, installedDir);
};

const pinMicrobitHex = () => {
    const hexDir = path.join(root, 'static', 'microbit');
    const hexes = fs.existsSync(hexDir) ?
        fs.readdirSync(hexDir).filter(name => name.endsWith('.hex')) :
        [];
    if (hexes.length !== 1) {
        throw new Error(`Expected one firmware file in static/microbit, found ${hexes.length}`);
    }
    const requirePath = `./${path.posix.relative('src/generated', `static/microbit/${hexes[0]}`)}`;
    const body = [
        '// This file is generated by scripts/host-extensions.mjs',
        '// Do not edit this file directly',
        '// This file relies on a loader to turn this `require` into a URL',
        `module.exports = require('${requirePath}');`,
        ''
    ].join('\n');
    const generatedDir = path.join(root, 'src', 'generated');
    fs.mkdirSync(generatedDir, {recursive: true});
    const generatedFile = path.join(generatedDir, 'microbit-hex-url.cjs');
    if (fs.existsSync(generatedFile) && fs.readFileSync(generatedFile, 'utf8') === body) {
        return;
    }
    fs.writeFileSync(generatedFile, body);
};

const registerArduinoUno = () => {
    const manager = path.join(root, 'node_modules', 'scratch-vm', 'src', 'extension-support', 'extension-manager.js');
    if (!fs.existsSync(manager)) return;
    const text = fs.readFileSync(manager, 'utf8');
    if (text.includes('arduinoUno:')) return;
    const needle = "    gdxfor: () => require('../extensions/scratch3_gdx_for')\n};";
    if (!text.includes(needle)) {
        throw new Error('Não foi possível registrar a extensão Arduino Uno.');
    }
    fs.writeFileSync(manager, text.replace(
        needle,
        "    gdxfor: () => require('../extensions/scratch3_gdx_for'),\n    arduinoUno: () => require('../extensions/scratch3_arduino_uno')\n};"
    ));
};

restoreBundledExtensions();
registerArduinoUno();
pinMicrobitHex();
